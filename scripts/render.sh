#!/usr/bin/env bash
# Renders each Plane overlay into gitops/environments/<env>/manifests.yaml, the plain manifests
# Argo CD syncs. Argo never runs Kustomize or Helm: an open regression (argo-cd #30215) makes
# --enable-helm unreliable at sync time.
#
#   scripts/render.sh           write the rendered files
#   scripts/render.sh --check   write nothing, exit non-zero if a rendered file is out of date
# shellcheck source-path=SCRIPTDIR source=lib/common.sh
source "$(dirname "$0")/lib/common.sh"

ENVIRONMENTS=(dev prod-sim)

case "${1:-}" in
  "") CHECK=false ;;
  --check) CHECK=true ;;
  *) die "usage: $0 [--check]" ;;
esac

# Rendering writes a few hundred KiB, so this only catches a host that is already full.
guard_disk 1

render() {
  local env="$1" out="$2"
  {
    printf '# GENERATED by scripts/render.sh from helm/plane/overlays/%s. Do not edit.\n' "$env"
    printf '# Change the overlay or helm/plane/components/hardening, then run: make render\n'
    kustomize build --enable-helm --helm-command "$ROOT/.tools/bin/helm" \
      "$ROOT/helm/plane/overlays/$env"
  } >"$out"
}

# Kustomize does not fail when a patch target matches nothing, so a chart change could silently
# undo a hard rule. These are the rules that must hold even if nothing else catches them.
assert_rules() {
  local env="$1" file="$2" bad
  if grep -qE '^kind: Secret$' "$file"; then
    die "$env: rendered manifests contain a kind: Secret"
  fi
  if bad="$(grep -E '^[[:space:]-]*image: ' "$file" | grep -v '@sha256:')"; then
    die "$env: image not pinned by digest: $bad"
  fi
  if grep -qE '^[[:space:]]+timestamp: ' "$file"; then
    die "$env: the chart's timestamp annotation survived, so renders are not deterministic"
  fi
}

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

stale=0
for env in "${ENVIRONMENTS[@]}"; do
  target="$ROOT/gitops/environments/$env/manifests.yaml"
  rendered="$WORK/$env.yaml"
  render "$env" "$rendered"
  assert_rules "$env" "$rendered"

  if [[ "$CHECK" == true ]]; then
    if diff -u "$target" "$rendered" >"$WORK/$env.diff" 2>&1; then
      ok "$env is up to date"
    else
      cat "$WORK/$env.diff" >&2
      warn "$env is out of date: run make render and commit the result"
      stale=1
    fi
  else
    mkdir -p "$(dirname "$target")"
    mv "$rendered" "$target"
    ok "rendered ${target#"$ROOT"/}"
  fi
done

exit "$stale"
