const ILLUSTRATION = {
  inbox: ["merge"],
  search: ["rings"],
};

// A chart symbol in crop marks, on a 120-unit square. k thickens lines so they survive the size each slot draws.
function drawing(name, opts, k) {
  const g = pen(PALETTE, k);
  const corner = (x, y, dx, dy) => `M${x + dx} ${y}H${x}V${y + dy}`;
  const crops = [corner(-58, -58, 8, 8), corner(58, -58, -8, 8), corner(-58, 58, 8, -8), corner(58, 58, -8, -8)].join("");
  return `<path d="${crops}" fill="none" stroke="${PALETTE.hair}" stroke-width="${n(0.5 * k)}"/>` + MOTIFS[name](g, opts ?? {});
}

function table(entries, k) {
  return Object.entries(entries)
    .map(([key, [name, opts]]) => `  ${JSON.stringify(key)}: ${JSON.stringify(drawing(name, opts, k))},`)
    .join("\n");
}

// The exports and helpers below are upstream's, so upstream's copyright line stays.
const source = `/**
 * Copyright (c) 2023-present Plane Software, Inc. and contributors
 * Copyright (c) 2026 Bereket Abera
 * SPDX-License-Identifier: AGPL-3.0-only
 * See the LICENSE file for details.
 *
 * GENERATED by apps/wayline/assets/generate-empty-states.mjs. Regenerate rather than edit. Replaces upstream's
 * registry of the same name with the same exports, so empty states draw flat chart symbols.
 * The strings are static drawings from that script, never user input.
 */

import React from "react";
import type {
  CompactAssetType,
  DetailedAssetType,
  HorizontalStackAssetType,
  IllustrationAssetType,
  VerticalStackAssetType,
} from "./asset-types";

type TChartAsset = React.ComponentType<{ className?: string }>;

function chartAsset(drawing: string, size: number): TChartAsset {
  return function ChartAsset({ className }: { className?: string }) {
    return (
      <svg
        width={size}
        height={size}
        viewBox="-60 -60 120 120"
        fill="none"
        xmlns="http://www.w3.org/2000/svg"
        aria-hidden="true"
        focusable="false"
        className={className}
        dangerouslySetInnerHTML={{ __html: drawing }}
      />
    );
  };
}

const assets = <K extends string>(drawings: Record<K, string>, size: number) =>
  Object.fromEntries(Object.entries(drawings).map(([key, drawing]) => [key, chartAsset(drawing as string, size)])) as Record<
    K,
    TChartAsset
  >;

export const HORIZONTAL_STACK_ASSETS: Record<HorizontalStackAssetType, TChartAsset> = assets(
  {
${table(HORIZONTAL, 1.4).replace(/^/gm, "  ")}
  },
  112
);

export const VERTICAL_STACK_ASSETS: Record<VerticalStackAssetType, TChartAsset> = assets(
  {
${table(VERTICAL, 1).replace(/^/gm, "  ")}
  },
  160
);

export const ILLUSTRATION_ASSETS: Record<IllustrationAssetType, TChartAsset> = assets(
  {
${table(ILLUSTRATION, 1).replace(/^/gm, "  ")}
  },
  160
);

// Helper functions to get assets
export const getCompactAsset = (assetKey: CompactAssetType, className?: string): React.ReactNode => {
  const AssetComponent =
    HORIZONTAL_STACK_ASSETS[assetKey as HorizontalStackAssetType] || ILLUSTRATION_ASSETS[assetKey as IllustrationAssetType];

  if (!AssetComponent) {
    console.warn(\`Asset "\${assetKey}" not found in compact asset registry\`);
    return null;
  }

  return <AssetComponent className={className} />;
};

export const getDetailedAsset = (assetKey: DetailedAssetType, className?: string): React.ReactNode => {
  const AssetComponent =
    VERTICAL_STACK_ASSETS[assetKey as VerticalStackAssetType] || ILLUSTRATION_ASSETS[assetKey as IllustrationAssetType];

  if (!AssetComponent) {
    console.warn(\`Asset "\${assetKey}" not found in detailed asset registry\`);
    return null;
  }

  return <AssetComponent className={className} />;
};
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, source);
console.log(`empty states: ${Object.keys(HORIZONTAL).length} compact, ${Object.keys(VERTICAL).length} detailed, ${Object.keys(ILLUSTRATION).length} illustrations, ${source.length} bytes`);
