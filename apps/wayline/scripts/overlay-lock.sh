# overlay.lock records, for every overlay file, what upstream had at that path when it was last looked at.
# rsync copies a file to whatever path it names, so without this a replaced file that upstream moved
# becomes a harmless-looking orphan while the real one ships upstream's artwork, and an upstream change to
# a file we replace whole goes unseen.
#
#   apps/wayline/scripts/overlay-lock.sh --check <pristine tree>   apply.sh runs this before the overlay
#   apps/wayline/scripts/overlay-lock.sh --update                  at bump time, after reading what --check named
#
# Each line is <kind> TAB <upstream blob or -> TAB <path>:
#   replace   the overlay replaces this upstream file whole
#   new       upstream has nothing at this path
#   origin    not in the overlay: a file ours were derived from, which is reported by checks/upgrade-check.sh
# shellcheck source=lib.sh
source "$(dirname "$0")/lib.sh"

# Upstream's files that runtime/ and scripts/build.sh were derived from.
ORIGINS=(
  apps/web/nginx/nginx.conf apps/admin/nginx/nginx.conf
  apps/web/Dockerfile.web apps/admin/Dockerfile.admin apps/space/Dockerfile.space apps/api/Dockerfile.api
)

tree_listing() { # <commit-ish in the cache>: path TAB blob
  wgit -C "$UPSTREAM_CACHE" ls-tree -r -z "$1" | tr '\0' '\n' | awk -F'\t' '{ split($1, m, " "); print $2 "\t" m[3] }' | LC_ALL=C sort
}
overlay_files() { (cd "$OVERLAY" && find . -type f ! -name .DS_Store | sed 's|^\./||' | LC_ALL=C sort); }

render() { # what the lock should say for this upstream commit
  local listing="$1" f blob
  while IFS= read -r f; do
    blob="$(awk -F'\t' -v p="$f" '$1 == p { print $2; exit }' "$listing")"
    if [[ -n "$blob" ]]; then printf 'replace\t%s\t%s\n' "$blob" "$f"; else printf 'new\t-\t%s\n' "$f"; fi
  done < <(overlay_files)
  for f in "${ORIGINS[@]}"; do
    blob="$(awk -F'\t' -v p="$f" '$1 == p { print $2; exit }' "$listing")"
    printf 'origin\t%s\t%s\n' "${blob:--}" "$f"
  done
}

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
"$WAYLINE/scripts/fetch.sh" --cache-only
tree_listing "$UPSTREAM_COMMIT" >"$WORK/listing"
render "$WORK/listing" >"$WORK/lock"

case "${1:-}" in
  --update)
    {
      printf '# Generated by apps/wayline/scripts/overlay-lock.sh --update, against %s (%s).\n' "$UPSTREAM_TAG" "$UPSTREAM_COMMIT"
      cat "$WORK/lock"
    } >"$OVERLAY_LOCK"
    ok "overlay.lock: $(grep -c '^replace' "$WORK/lock") replaced, $(grep -c '^new' "$WORK/lock") new, $(grep -c '^origin' "$WORK/lock") origins"
    ;;
  --check)
    [[ -f "$OVERLAY_LOCK" ]] || die "no overlay.lock, run apps/wayline/scripts/overlay-lock.sh --update"
    # Origins are not checked here: a changed nginx.conf upstream is something to read, not a broken build.
    grep -v '^origin' "$WORK/lock" | LC_ALL=C sort >"$WORK/want"
    grep -Ev '^(#|origin)' "$OVERLAY_LOCK" | LC_ALL=C sort >"$WORK/have"
    if ! cmp -s "$WORK/want" "$WORK/have"; then
      warn "the overlay no longer matches what upstream has at these paths:"
      awk -F'\t' '
        NR == FNR { have[$3] = $1; haveblob[$3] = $2; next }
        { want[$3] = $1; wantblob[$3] = $2 }
        END {
          for (p in have) {
            if (!(p in want)) { print "    " p ": in overlay.lock but not in the overlay"; continue }
            if (have[p] == want[p] && haveblob[p] == wantblob[p]) continue
            if (have[p] == "replace" && want[p] == "new") print "    " p ": upstream moved or deleted this, so the overlay file is an orphan and the real one ships upstream art"
            else if (have[p] == "replace") print "    " p ": upstream changed the file this replaces whole. Read the change, then merge it by hand"
            else print "    " p ": upstream now has a file at this path, which the overlay would overwrite"
          }
          for (p in want) if (!(p in have)) print "    " p ": in the overlay but not in overlay.lock"
        }' "$WORK/have" "$WORK/want" | LC_ALL=C sort >&2
      die "overlay.lock does not match. Fix the paths above, then run apps/wayline/scripts/overlay-lock.sh --update"
    fi
    ok "overlay.lock matches $UPSTREAM_TAG: $(grep -c '^replace' "$WORK/want") replaced, $(grep -c '^new' "$WORK/want") new"
    ;;
  *)
    die "usage: $0 --check <tree> | --update"
    ;;
esac
